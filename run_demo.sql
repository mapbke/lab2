CREATE TABLE lab2_demo.warehouses (
    warehouse_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    address TEXT NOT NULL,
    manager_name TEXT
);

CREATE TABLE lab2_demo.placements (
    warehouse_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    package_quantity INTEGER NOT NULL CHECK (package_quantity > 0),
    shipment_date DATE NOT NULL,
    weight_kg NUMERIC(10, 2) NOT NULL CHECK (weight_kg >= 0),
    is_received BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (warehouse_id, product_id, shipment_date),
    FOREIGN KEY (warehouse_id) REFERENCES lab2_demo.warehouses(warehouse_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

